/*
  scripts/gen-specs-migration.mjs   (opt cycle 11 — scorecard 4.4)
  Writes supabase/migrations/0038_product_specs.sql from src/data/productSpecs.js:
  an UPDATE-ONLY migration that fills sequence / molecular weight / CAS where
  the row has none (coalesce) — never overwrites a value the owner entered in
  the Control Room. Byte-compared by scripts/test-product-specs.mjs, so re-run
  this after editing productSpecs.js and commit both.
  Run: node scripts/gen-specs-migration.mjs
*/
import fs from "node:fs";
import { PRODUCT_SPECS } from "../src/data/productSpecs.js";

const q = (v) => `'${String(v).replace(/'/g, "''")}'`;
const lines = [
  "-- 0038_product_specs.sql   (opt cycle 11 — scorecard 4.4)",
  "-- GENERATED by scripts/gen-specs-migration.mjs from src/data/productSpecs.js —",
  "-- do not hand-edit; re-run the script. Every value is a transcription of a",
  "-- verified source (named in productSpecs.js); nothing is derived. UPDATE only,",
  "-- coalesce: a value already present (entered in the Control Room) is kept.",
  "-- Idempotent. Additive in effect (no column, no row created).",
  "",
];
for (const [id, s] of Object.entries(PRODUCT_SPECS)) {
  const sets = [];
  if (s.sequence) sets.push(`peptide_sequence = coalesce(peptide_sequence, ${q(s.sequence)})`);
  if (s.molecularWeight) sets.push(`molecular_weight = coalesce(molecular_weight, ${q(s.molecularWeight)})`);
  if (s.cas) sets.push(`cas_number = coalesce(cas_number, ${q(s.cas)})`);
  if (!sets.length) continue;
  lines.push(`update public.products set ${sets.join(", ")} where id = ${q(id)};`);
}
lines.push("");
export const SQL = lines.join("\n");
if (process.argv[1] && import.meta.url.endsWith(process.argv[1].split(/[\\/]/).pop())) {
  fs.writeFileSync("supabase/migrations/0038_product_specs.sql", SQL);
  console.log(`wrote supabase/migrations/0038_product_specs.sql (${Object.keys(PRODUCT_SPECS).length} products)`);
}
