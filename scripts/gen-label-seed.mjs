/*
  scripts/gen-label-seed.mjs
  Generates supabase/migrations/0020_label_configs_seed.sql — a draft
  label_config for EVERY catalog product/variant, so the whole catalog is
  covered in the Label Studio in one shot (the SQL equivalent of the studio's
  "Seed missing drafts" button).

  Seed rules come from lib/labelSeed.js (blend component NAMES from catalog
  data with EMPTY quantities; storage UNVERIFIED; lot/dates BLANK — nothing
  fabricated). Default direction Core Black. Each row gets a unique crypto
  Crockford-base32 verification code. Idempotent: inserts only where the
  product+variant has no config yet (safe to run alongside manually-created
  labels or the admin Seed button).

  Run: node scripts/gen-label-seed.mjs
*/
import fs from "node:fs";
import path from "node:path";
import { randomBytes } from "node:crypto";
import { getAllProducts } from "../src/data/tier1Catalog.js";
import { seedFieldsForVariant } from "../lib/labelSeed.js";

const CROCKFORD = "0123456789ABCDEFGHJKMNPQRSTVWXYZ";
const seen = new Set();
function code() {
  for (;;) {
    const b = randomBytes(13);
    let s = "";
    for (let i = 0; i < 13; i++) s += CROCKFORD[b[i] % 32];
    if (!seen.has(s)) {
      seen.add(s);
      return s;
    }
  }
}

const q = (s) => (s === null || s === undefined ? "null" : `'${String(s).replace(/'/g, "''")}'`);
const jb = (v) => (v == null ? "null" : `'${JSON.stringify(v).replace(/'/g, "''")}'::jsonb`);

const rows = [];
for (const p of getAllProducts()) {
  for (const v of p.variants) {
    const f = seedFieldsForVariant({ id: p.id, name: p.name }, v);
    rows.push(
      `  (${q(f.product_id)}, ${q(f.variant_id)}, ${q(f.template_id)}, ${q(f.default_preset)}, 'draft', ` +
        `${q(f.display_name)}, ${q(f.quantity_label)}, ${q(f.material_type)}, ${jb(f.composition)}, ` +
        `${q(f.sku)}, ${q(f.barcode_value)}, ${q(code())}, false, false)`
    );
  }
}

const sql = `-- supabase/migrations/0020_label_configs_seed.sql
-- GENERATED by scripts/gen-label-seed.mjs — do not hand-edit; re-run the script.
--
-- Seeds a DRAFT label_config for every catalog product/variant (${rows.length} labels),
-- so the entire catalog is covered in the Label Studio. Mirrors the studio's
-- "Seed missing drafts" action and the seedFieldsForVariant rules:
--   * name / quantity / SKU / barcode from the live catalog
--   * blend COMPONENT NAMES from catalog data with EMPTY quantities
--     (render "pending administrative input" until the owner fills them)
--   * storage UNVERIFIED (safe placeholder prints until confirmed)
--   * lot / MFG / EXP BLANK (owner enters real batch data; nothing fabricated)
--   * default direction Core Black (switch per label in the studio)
--   * unique crypto Crockford-base32 verification code per label
--
-- Idempotent: inserts ONLY where the product+variant has no config yet — safe
-- to run alongside labels you already created by hand or via the Seed button.
-- Requires migration 0018 (label_configs).

insert into public.label_configs
  (product_id, variant_id, template_id, default_preset, status,
   display_name, quantity_label, material_type, composition,
   sku, barcode_value, verification_code, storage_source_verified, recalled)
select s.* from (values
${rows.join(",\n")}
) as s(product_id, variant_id, template_id, default_preset, status,
       display_name, quantity_label, material_type, composition,
       sku, barcode_value, verification_code, storage_source_verified, recalled)
where not exists (
  select 1 from public.label_configs lc
  where lc.product_id = s.product_id
    and lc.variant_id is not distinct from s.variant_id
);

-- Summary: ${rows.length} draft labels seeded (idempotent).
`;

const dest = path.join(process.cwd(), "supabase", "migrations", "0020_label_configs_seed.sql");
fs.writeFileSync(dest, sql);
console.log(`[label-seed] wrote ${dest}\n[label-seed] ${rows.length} draft labels`);
