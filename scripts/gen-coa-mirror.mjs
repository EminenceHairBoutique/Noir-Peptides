/*
  scripts/gen-coa-mirror.mjs   (opt cycle 11 — scorecards 4.4 / 4.6)
  Writes src/data/coaSeed.js — a static mirror of the certificates seeded by
  supabase/migrations/0019_janoshik_coas.sql (real, published Janoshik
  results already committed to this repo) — so a build WITHOUT database env
  (CI, the sandbox) still prerenders /test-results and the per-product
  batch-history permalinks from the same rows the database holds. A build
  WITH env keeps fetching the live rows. Byte-compared by
  scripts/test-coa-seed-sync.mjs; re-run after editing 0019.
  Run: node scripts/gen-coa-mirror.mjs
*/
import fs from "node:fs";

const SRC = "supabase/migrations/0019_janoshik_coas.sql";
const sql = fs.readFileSync(SRC, "utf8");
const insert = sql.slice(sql.indexOf("insert into public.coas"));
const cols = insert.match(/\(([^)]*)\)\s*values/s)[1].split(",").map((c) => c.trim());
// The statement ends at the LAST ");" — a comment line inside the values may carry a ";".
const body = insert.slice(insert.indexOf("values") + 6, insert.lastIndexOf(");") + 1);
const rows = [];
// One certificate per line: "  ('product', …)," — comment lines are skipped.
for (const line of body.split("\n")) {
  const m = line.match(/^\s*\((.*)\)[,;]?\s*$/);
  if (!m || !/^\s*\('/.test(line)) continue;
  const tuple = m[1];
  const vals = [...tuple.matchAll(/'((?:[^']|'')*)'|(-?\d+(?:\.\d+)?)|\b(true|false|null)\b/g)].map((v) => (v[1] !== undefined ? v[1].replace(/''/g, "'") : v[2] !== undefined ? Number(v[2]) : v[3] === "null" ? null : v[3] === "true"));
  if (vals.length !== cols.length) throw new Error(`row parse mismatch: ${tuple.slice(0, 60)}`);
  rows.push(Object.fromEntries(cols.map((c, i) => [c, vals[i]])));
}
export const COA_SEED = rows.map((r, i) => ({
  id: `seed-${i + 1}`, // never a number: a numeric id could collide with a live row (batch_tests lookups)
  product_id: r.product_id, batch_number: r.batch_number, lot_number: r.lot_number, lab_name: r.lab_name,
  file_url: r.file_url, cas_number: null, purity_percent: r.purity_percent, hplc: r.hplc, mass_spec: r.mass_spec,
  ms_confirmed: r.ms_confirmed, endotoxin: null, tested_at: r.tested_at, is_published: r.is_published, created_at: null, // the database's own timestamp — never synthesised
  lab_id: null, lab_lookup_code: null, purity_operator: null, net_peptide_content_mg: null, label_claim_mg: null, published_on: null, status: null, file_path: null,
}));
export const MODULE = `// src/data/coaSeed.js — GENERATED by scripts/gen-coa-mirror.mjs from
// supabase/migrations/0019_janoshik_coas.sql. Do not hand-edit.
// The ${COA_SEED.length} certificates the seed publishes, mirrored so a build or a
// client without database access shows the same real, published lab results
// the database holds (opt cycle 11). Never a substitute when the database
// is reachable; never a place to add a certificate (that is the Control Room).
export const COA_SEED = ${JSON.stringify(COA_SEED, null, 2)};

export const COA_SEED_SOURCE = "supabase/migrations/0019_janoshik_coas.sql";
`;
if (process.argv[1] && import.meta.url.endsWith(process.argv[1].split(/[\\/]/).pop())) {
  fs.writeFileSync("src/data/coaSeed.js", MODULE);
  console.log(`wrote src/data/coaSeed.js (${COA_SEED.length} certificates across ${new Set(COA_SEED.map((r) => r.product_id)).size} products)`);
}
